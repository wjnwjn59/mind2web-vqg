"""Audit a built TreeVQG JSONL before it is used (or released) as a benchmark.

``stats.json`` written by the builder answers "how much data came out". This module
answers the harder question from ``docs/treevqg/plan/09-dataset-audit.md``: *is the data
any good?* It looks for the failure modes that inflate a template-generated benchmark:

* **answer leakage** — the answer is already visible in the prompt (`input` carries a
  text outline of the tree, including the anchor's label);
* **template collapse** — thousands of rows but only a handful of distinct questions;
* **level contamination** — an L1 question that talks about a page/form, or an L3
  question that only asks for text on the screenshot;
* **balance / provenance** — one website or one level dominating the corpus;
* **missing evidence** — no screenshot, empty answer, no bbox for a region question.

Everything is stdlib-only and deterministic. Usage::

    uv run python -m mind2web_vqg.treevqg.audit \
        --examples data/processed/treevqg/test_task/examples.jsonl \
        --out outputs/treevqg_audit/test_task

It writes ``audit.json`` + ``audit.md`` and prints a short summary. The exit code is 0
when the audit ran; findings are reported as warnings, not failures, because a low score
here is a research result, not a crash.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any

from mind2web_vqg.cli import ensure_utf8
from mind2web_vqg.treevqg import LEVELS
from mind2web_vqg.treevqg import io as tree_io

#: Answers that carry no information even when they are "correct".
GENERIC_ANSWERS: frozenset[str] = frozenset(
    {"button", "click", "yes", "no", "none", "null", "n/a", "element", "item", "text"}
)

_QUOTED = re.compile(r'"[^"]*"')
_WORD = re.compile(r"[a-z0-9]+")

#: Relation words that make an L2 question about a container, not a lone element.
_CONTAINER_MARKERS: tuple[str, ...] = (" in the ", " inside ", " within ", " contain")

#: Workflow markers that make an L3 question about progress / state.
_WORKFLOW_MARKERS: tuple[str, ...] = (
    "step",
    "completed",
    "progress",
    "currently",
    "already",
    "page or section",
)


def normalize(text: Any) -> str:
    """Casefold, drop punctuation, collapse whitespace."""
    return " ".join(_WORD.findall(str(text or "").casefold()))


def _normalized_with_spaces(text: Any) -> str:
    """Like :func:`normalize`, but keeps word boundaries (for substring tests)."""
    return f" {normalize(text)} "


def skeleton(question: Any, task: Any = "", answer: Any = "") -> str:
    """Template skeleton of a question: quoted spans and the task/answer replaced.

    Two rows generated by the same rule share a skeleton even when they are about
    different pages, so ``unique / n`` measures *semantic* diversity rather than the
    number of distinct labels in the corpus.
    """
    text = str(question or "")
    text = _QUOTED.sub(" <slot> ", text)
    for value in (task, answer):
        value = str(value or "").strip()
        if len(value) >= 3:
            text = re.sub(re.escape(value), " <slot> ", text, flags=re.IGNORECASE)
    return normalize(text)


def prefix(question: Any, n: int = 4) -> str:
    """First ``n`` normalized words — the cheap "is it one template?" signal."""
    return " ".join(normalize(question).split()[:n])


def answer_in_question(row: dict[str, Any]) -> bool:
    """True when the gold answer is literally part of the question."""
    answer = normalize(row.get("answer"))
    if len(answer) < 2:
        return False
    return answer in normalize(row.get("target"))


def answer_in_input(row: dict[str, Any]) -> bool:
    """True when the answer is copied from the prompt (tree outline) — the main leak.

    Pure numbers are skipped: a count like ``10`` occurs in almost any page dump, so a
    substring hit says nothing about leakage. Count answers are covered separately by the
    ``trajectory_answer_rate`` statistic instead.
    """
    normalized = normalize(row.get("answer"))
    if len(normalized) < 2 or normalized.isdigit():
        return False
    return f" {normalized} " in _normalized_with_spaces(row.get("input"))


def _level_marker(level: str, question: Any) -> bool | None:
    """Does the question use the relational/contextual cue its level requires?"""
    text = f" {normalize(question)} "
    if level == "L1":
        return not any(word in text for word in _CONTAINER_MARKERS)
    if level == "L2":
        return any(word in text for word in _CONTAINER_MARKERS)
    if level == "L3":
        return any(word in text for word in _WORKFLOW_MARKERS)
    return None


def _mean(values: list[float]) -> float:
    return round(sum(values) / len(values), 2) if values else 0.0


def _median(values: list[float]) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    middle = len(ordered) // 2
    if len(ordered) % 2:
        return float(ordered[middle])
    return round((ordered[middle - 1] + ordered[middle]) / 2, 2)


def _pairs(count: int) -> int:
    """Number of unordered pairs in a group of ``count`` identical rows."""
    return count * (count - 1) // 2


def _top(counter: Counter[str], k: int = 10) -> list[dict[str, Any]]:
    return [{"value": value, "count": count} for value, count in counter.most_common(k)]


def audit_rows(rows: list[dict[str, Any]], *, sample_size: int = 3) -> dict[str, Any]:
    """Compute every audit number for a list of TreeVQG rows."""
    if not rows:
        raise ValueError("no rows to audit")

    by_level: dict[str, list[dict[str, Any]]] = {level: [] for level in LEVELS}
    for row in rows:
        level = str(row.get("level") or row.get("meta", {}).get("level") or "?")
        by_level.setdefault(level, []).append(row)

    totals = {
        "examples": len(rows),
        "actions": len({row.get("meta", {}).get("source_id") or row.get("id") for row in rows}),
        "tasks": len({row.get("meta", {}).get("annotation_id") for row in rows if row.get("meta")}),
        "websites": len({row.get("meta", {}).get("website") for row in rows if row.get("meta")}),
        "domains": len({row.get("meta", {}).get("domain") for row in rows if row.get("meta")}),
    }

    answer_types = Counter(str(row.get("meta", {}).get("answer_type")) for row in rows)
    answer_sources = Counter(str(row.get("meta", {}).get("answer_source")) for row in rows)
    hints = Counter(str(row.get("meta", {}).get("hint")) for row in rows)
    websites = Counter(str(row.get("meta", {}).get("website")) for row in rows if row.get("meta"))

    level_blocks: dict[str, Any] = {}
    for level, block in by_level.items():
        if not block:
            continue
        question_words = [len(normalize(row.get("target")).split()) for row in block]
        answer_words = [len(normalize(row.get("answer")).split()) for row in block]
        skeletons = Counter(
            skeleton(row.get("target"), row.get("meta", {}).get("task"), row.get("answer"))
            for row in block
        )
        exact = Counter(normalize(row.get("target")) for row in block)
        prefixes = Counter(prefix(row.get("target")) for row in block)
        markers = [
            _level_marker(level, row.get("target"))
            for row in block
            if _level_marker(level, row.get("target")) is not None
        ]
        level_blocks[level] = {
            "n": len(block),
            "share": round(len(block) / len(rows), 3),
            "question_words_mean": _mean(question_words),
            "question_words_median": _median(question_words),
            "question_words_over_40": sum(1 for value in question_words if value > 40),
            "answer_words_mean": _mean(answer_words),
            "empty_answer_rate": round(
                sum(1 for row in block if not normalize(row.get("answer"))) / len(block), 3
            ),
            "generic_answer_rate": round(
                sum(normalize(row.get("answer")) in GENERIC_ANSWERS for row in block)
                / len(block),
                3,
            ),
            "trajectory_answer_rate": round(
                sum(
                    str(row.get("meta", {}).get("answer_source")) == "trajectory"
                    for row in block
                )
                / len(block),
                3,
            ),
            "answer_in_question_rate": round(
                sum(answer_in_question(row) for row in block) / len(block), 3
            ),
            "answer_in_input_rate": round(
                sum(answer_in_input(row) for row in block) / len(block), 3
            ),
            "level_marker_rate": round(sum(markers) / len(markers), 3) if markers else None,
            "unique_question_rate": round(len(exact) / len(block), 3),
            "unique_skeleton_rate": round(len(skeletons) / len(block), 3),
            "n_skeletons": len(skeletons),
            "max_skeleton_share": round(
                skeletons.most_common(1)[0][1] / len(block), 3
            ),
            "skeleton_duplicate_pairs": sum(_pairs(count) for count in skeletons.values()),
            "exact_duplicate_pairs": sum(_pairs(count) for count in exact.values() if count > 1),
            "top_prefixes": _top(prefixes, 5),
            "answer_types": dict(
                Counter(str(row.get("meta", {}).get("answer_type")) for row in block)
            ),
            "answer_sources": dict(
                Counter(str(row.get("meta", {}).get("answer_source")) for row in block)
            ),
            "hints": dict(Counter(str(row.get("meta", {}).get("hint")) for row in block)),
            "anchor_roles": _top(
                Counter(str(row.get("meta", {}).get("anchor_role")) for row in block), 5
            ),
            "anchor_tags": _top(
                Counter(str(row.get("meta", {}).get("anchor_tag")) for row in block), 5
            ),
            "tree_nodes_mean": _mean(
                [float(row.get("meta", {}).get("tree_nodes") or 0) for row in block]
            ),
            "anchor_depth_mean": _mean(
                [float(row.get("meta", {}).get("anchor_depth") or 0) for row in block]
            ),
            "target_matched_rate": round(
                sum(bool(row.get("meta", {}).get("target_matched")) for row in block) / len(block),
                3,
            ),
        }

    # --- evidence on disk -------------------------------------------------- #
    images = [str(row.get("image") or "") for row in rows]
    missing_images = sum(1 for path in images if not path or not Path(path).is_file())
    bbox_anchors = 0
    bbox_questions = 0
    for row in rows:
        tree = row.get("tree") or {}
        anchor = tree.get("anchor")
        nodes = tree.get("nodes") or []
        node = nodes[anchor] if isinstance(anchor, int) and 0 <= anchor < len(nodes) else {}
        if node.get("bbox"):
            bbox_anchors += 1
        if str(row.get("meta", {}).get("answer_type")) == "region":
            bbox_questions += 1

    generic_answers = sum(normalize(row.get("answer")) in GENERIC_ANSWERS for row in rows)

    # --- samples to eyeball (first distinct skeleton per level) ------------ #
    samples: dict[str, list[dict[str, Any]]] = {}
    for level, block in by_level.items():
        seen: set[str] = set()
        picked: list[dict[str, Any]] = []
        for row in block:
            key = skeleton(row.get("target"), row.get("meta", {}).get("task"), row.get("answer"))
            if key in seen:
                continue
            seen.add(key)
            picked.append(
                {
                    "id": row.get("id"),
                    "task": row.get("meta", {}).get("task"),
                    "question": row.get("target"),
                    "answer": row.get("answer"),
                    "anchor_role": row.get("meta", {}).get("anchor_role"),
                    "anchor_tag": row.get("meta", {}).get("anchor_tag"),
                    "anchor_depth": row.get("meta", {}).get("anchor_depth"),
                    "answer_source": row.get("meta", {}).get("answer_source"),
                    "website": row.get("meta", {}).get("website"),
                }
            )
            if len(picked) >= sample_size:
                break
        samples[level] = picked

    totals.update(
        {
            "image_missing": missing_images,
            "image_missing_rate": round(missing_images / len(rows), 3),
            "bbox_anchor_rate": round(bbox_anchors / len(rows), 3),
            "region_question_count": bbox_questions,
            "generic_answer_rate": round(generic_answers / len(rows), 3),
            "trajectory_answer_rate": round(
                sum(
                    str(row.get("meta", {}).get("answer_source")) == "trajectory"
                    for row in rows
                )
                / len(rows),
                3,
            ),
            "answer_types": dict(answer_types),
            "answer_sources": dict(answer_sources),
            "hints": dict(hints),
            "top_websites": _top(websites, 10),
            "max_website_share": round(websites.most_common(1)[0][1] / len(rows), 3)
            if websites
            else 0.0,
        }
    )

    audit = {
        "totals": totals,
        "by_level": level_blocks,
        "samples": samples,
        "warnings": build_warnings(totals, level_blocks),
    }
    return audit


def build_warnings(totals: dict[str, Any], by_level: dict[str, Any]) -> list[str]:
    """Human-readable flags for the failure modes the audit is meant to catch."""
    warnings: list[str] = []
    if totals["max_website_share"] > 0.2:
        warnings.append(
            f"one website holds {totals['max_website_share']:.0%} of the rows "
            "(>20%): the corpus is site-skewed"
        )
    if totals["image_missing_rate"] > 0:
        warnings.append(
            f"{totals['image_missing']} row(s) have no screenshot on disk; a VLM baseline "
            "cannot see them"
        )
    if totals["generic_answer_rate"] > 0.05:
        warnings.append(
            f"{totals['generic_answer_rate']:.0%} of answers are generic words "
            "(button/yes/none): low information content"
        )
    for level, block in by_level.items():
        if block["answer_in_input_rate"] > 0.1:
            warnings.append(
                f"{level}: answer appears in the prompt for "
                f"{block['answer_in_input_rate']:.0%} of rows — the tree outline leaks it"
            )
        if block["answer_in_question_rate"] > 0.1:
            warnings.append(
                f"{level}: answer is inside the question for "
                f"{block['answer_in_question_rate']:.0%} of rows — trivial to copy"
            )
        if block["generic_answer_rate"] > 0.1:
            warnings.append(
                f"{level}: {block['generic_answer_rate']:.0%} of answers are generic "
                "words (button/yes/none) — the question can be answered from the role "
                "alone"
            )
        if block["trajectory_answer_rate"] > 0.5:
            warnings.append(
                f"{level}: {block['trajectory_answer_rate']:.0%} of answers come from the "
                "action history, not the screenshot — this level is not visually grounded"
            )
        if block["max_skeleton_share"] > 0.3:
            warnings.append(
                f"{level}: one skeleton covers {block['max_skeleton_share']:.0%} of rows "
                f"({block['n_skeletons']} skeleton(s) total) — the model can learn the "
                "template instead of the semantics"
            )
        top = block["top_prefixes"][0] if block["top_prefixes"] else None
        if top and top["count"] / block["n"] > 0.3:
            warnings.append(
                f"{level}: prefix '{top['value']}' covers {top['count'] / block['n']:.0%} "
                "of rows (>30%) — template bias"
            )
        if block["level_marker_rate"] is not None and block["level_marker_rate"] < 0.9:
            warnings.append(
                f"{level}: only {block['level_marker_rate']:.0%} of questions use the cue "
                "expected at this level — possible level contamination"
            )
    return warnings


def render_markdown(audit: dict[str, Any]) -> str:
    """A compact report a reader can scan before touching the numbers."""
    totals = audit["totals"]
    lines = [
        "# TreeVQG dataset audit",
        "",
        "## 1. Scope",
        "",
        "| metric | value |",
        "| --- | --- |",
        f"| examples | {totals['examples']:,} |",
        f"| actions | {totals['actions']:,} |",
        f"| tasks | {totals['tasks']:,} |",
        f"| websites / domains | {totals['websites']} / {totals['domains']} |",
        f"| screenshots missing | {totals['image_missing']:,} "
        f"({totals['image_missing_rate']:.1%}) |",
        f"| anchor with bbox | {totals['bbox_anchor_rate']:.1%} |",
        f"| region questions | {totals['region_question_count']:,} |",
        "",
        "## 2. Balance and quality by level",
        "",
        "| level | n | share | words/q | answer in prompt | answer in q "
        "| generic A | trajectory A | skeletons (max share) | level cue |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for level in LEVELS:
        block = audit["by_level"].get(level)
        if not block:
            lines.append(f"| {level} | 0 | 0% | – | – | – | – | – |")
            continue
        cue = "–" if block["level_marker_rate"] is None else f"{block['level_marker_rate']:.0%}"
        lines.append(
            f"| {level} | {block['n']:,} | {block['share']:.0%} | "
            f"{block['question_words_mean']:.1f} | {block['answer_in_input_rate']:.0%} | "
            f"{block['answer_in_question_rate']:.0%} | "
            f"{block['generic_answer_rate']:.0%} | "
            f"{block['trajectory_answer_rate']:.0%} | "
            f"{block['n_skeletons']} ({block['max_skeleton_share']:.0%}) | {cue} |"
        )

    lines += [
        "",
        "`answer in prompt` is the important leak: ``input`` contains a text outline of "
        "the UI tree, so an answer copied from that outline can be asked without looking "
        "at the screenshot.",
        "",
        "## 3. Answer types and provenance",
        "",
        f"- answer types: `{totals['answer_types']}`",
        f"- answer sources: `{totals['answer_sources']}`",
        f"- hints: `{totals['hints']}`",
        "- most frequent websites: "
        + ", ".join(
            "{} ({})".format(item["value"], item["count"]) for item in totals["top_websites"][:5]
        ),
        "",
        "## 4. Warnings",
        "",
    ]
    if audit["warnings"]:
        lines += [f"- {warning}" for warning in audit["warnings"]]
    else:
        lines.append("- none")

    lines += ["", "## 5. Samples (one per distinct template)", ""]
    for level in LEVELS:
        block = audit["samples"].get(level) or []
        if not block:
            continue
        lines.append(f"### {level}")
        for sample in block:
            lines += [
                f"- **Q:** {sample['question']}",
                f"  - A: `{sample['answer']}`  "
                f"(anchor `{sample['anchor_role']}` at depth {sample['anchor_depth']}, "
                f"answer from {sample['answer_source']})",
                f"  - task: {sample['task']}",
            ]
        lines.append("")
    return "\n".join(lines)


def audit_file(
    examples: str | Path,
    *,
    out_dir: str | Path | None = None,
    sample_size: int = 3,
) -> dict[str, Any]:
    """Audit one ``examples.jsonl`` and write ``audit.json`` + ``audit.md``."""
    path = Path(examples)
    rows = tree_io.read_jsonl(path)
    audit = audit_rows(rows, sample_size=sample_size)
    audit["source"] = str(path)
    out = Path(out_dir) if out_dir else path.parent
    tree_io.write_json(audit, out / "audit.json")
    (out / "audit.md").write_text(render_markdown(audit), encoding="utf-8")
    return audit


def main(argv: list[str] | None = None) -> int:
    ensure_utf8()
    parser = argparse.ArgumentParser(description="Audit a built TreeVQG JSONL.")
    parser.add_argument(
        "--examples", type=Path, required=True, help="path to a TreeVQG examples.jsonl"
    )
    parser.add_argument(
        "--out", type=Path, default=None, help="output directory (default: next to the input)"
    )
    parser.add_argument("--samples", type=int, default=3, help="samples per level (default 3)")
    args = parser.parse_args(argv)

    audit = audit_file(args.examples, out_dir=args.out, sample_size=args.samples)
    totals = audit["totals"]
    print(
        f"[audit] {totals['examples']:,} example(s) from {totals['tasks']:,} task(s), "
        f"{totals['websites']} website(s)"
    )
    for level in LEVELS:
        block = audit["by_level"].get(level)
        if block:
            print(
                f"  {level} n={block['n']:,} answer-in-prompt={block['answer_in_input_rate']:.0%} "
                f"skeletons={block['n_skeletons']}"
            )
    for warning in audit["warnings"]:
        print(f"  ! {warning}")
    print(f"[audit] -> {Path(args.out) if args.out else Path(args.examples).parent}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
