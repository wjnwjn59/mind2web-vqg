"""Prompt templates for the question generation (VQG) task.

The **live** prompts for the built examples are generated by
:func:`mind2web_vqg.data.vqg.build_input` (instruction + the user's task). This module
keeps a plain-string mirror of that instruction for experiments in `notebooks/`; the
`question_gen.json` files are not read by the pipeline yet.
"""

from __future__ import annotations

import json

from mind2web_vqg.paths import PROMPT_DIR

#: Default template — mirrors `data/vqg.py::INSTRUCTION`.
DEFAULT_TEMPLATE = """\
You are shown a screenshot of a web page. Ask exactly one question about the page
whose answer can be read from the screenshot, focusing on {focus}.
The user's task is: {task}
Output only the question.
"""


def load_prompt(name: str = "question_gen.json") -> dict:
    """Read a prompt JSON file from ``src/mind2web_vqg/prompts``."""
    with open(PROMPT_DIR / name, encoding="utf-8") as f:
        return json.load(f)


__all__ = ["DEFAULT_TEMPLATE", "load_prompt"]
